"""Generate docs/rules.md from the rule catalogue in the source code.

The rule text lives in one place (the ``Rule`` objects in
``src/reposentinel/checks``); this script turns it into documentation, and a
test fails if docs/rules.md is out of date.

Usage:
    python scripts/generate_rules_doc.py          # rewrite docs/rules.md
    python scripts/generate_rules_doc.py --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from reposentinel.checks import default_checks

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "rules.md"

HEADER = """\
# RepoSentinel rule reference

<!-- Generated by scripts/generate_rules_doc.py from the rule definitions in
     src/reposentinel/checks/. Edit those, then re-run the script. -->

Every finding is a **potential indicator** that a person should review. No
rule confirms that a vulnerability is exploitable or that a credential is
valid, and no rule contacts any external service.

* **Severity** describes the likely impact *if* the finding is a true
  positive: `high` (direct compromise of credentials, code or CI is plausible),
  `medium` (a meaningful weakness or exposure that usually needs another
  factor), `low` (hardening opportunity), `info` (worth knowing, probably fine).
* **Confidence** describes how likely the match is a true positive, based on
  how distinctive the pattern is.
* Rule IDs are stable. Findings imported from an optional integration use the
  tool's own rule name with a prefix, for example `gitleaks:github-pat`.
* The **rule version** increases whenever a rule's matching changes.
  `reposentinel compare` reports findings of a rule whose version differs
  between the two scans as "Not comparable".
* **When a re-check no longer detects it** says what "Not detected on
  re-check" can *not* show for that rule. No re-check shows that a problem
  is fixed.

| Rule | Severity | Confidence | Title |
|---|---|---|---|
"""


def render_rules_markdown() -> str:
    rows: list[str] = []
    sections: list[str] = []
    pairs = sorted(
        ((rule, check.id) for check in default_checks() for rule in check.rules),
        key=lambda pair: pair[0].id,
    )
    for rule, check_id in pairs:
        anchor = rule.id.lower()
        rows.append(
            f"| [{rule.id}](#{anchor}) | {rule.severity.value} | {rule.confidence.value} "
            f"| {rule.title} |"
        )
        parts = [
            f"## {rule.id}",
            "",
            f"**{rule.title}**: check `{check_id}`, default severity `{rule.severity.value}`, "
            f"confidence `{rule.confidence.value}`, rule version {rule.version}.",
            "",
            f"**What it detects.** {rule.description}",
            "",
            f"**Why this severity.** {rule.severity_rationale}",
            "",
            f"**How to fix.** {rule.remediation}",
            "",
            f"**Limitations and false positives.** {rule.limitations}",
            "",
            f"**When a re-check no longer detects it.** {rule.recheck_limits}",
        ]
        if rule.references:
            parts += ["", "**References:** " + ", ".join(f"<{url}>" for url in rule.references)]
        sections.append("\n".join(parts))
    return HEADER + "\n".join(rows) + "\n\n" + "\n\n".join(sections) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/rules.md")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    content = render_rules_markdown()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(
                "docs/rules.md is out of date; run scripts/generate_rules_doc.py", file=sys.stderr
            )
            return 1
        print("docs/rules.md is up to date")
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
